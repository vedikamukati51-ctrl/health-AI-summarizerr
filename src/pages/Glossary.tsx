import { useState } from "react";
import { api } from "../services/api";
import type { GlossaryData } from "../types";

export default function Glossary() {
  const [term, setTerm] = useState("");
  const [result, setResult] = useState<GlossaryData | null>(null);
  const [loading, setLoading] = useState(false);

  async function explain() {
    if (!term.trim()) return;
    setLoading(true);
    try {
      setResult(await api.explainTerm(term.trim()));
    } catch {
      setResult({
        definition: "The backend could not be reached. Start the Express server and try again.",
        whyItMatters: "The live definition is generated by the backend AI service.",
      });
    } finally {
      setLoading(false);
    }
  }

  return (
    <section className="page">
      <span className="eyebrow">FEATURE 16</span>
      <h2>Medical term glossary</h2>
      <p>Ask for a patient-friendly explanation of a medical term.</p>

      <div className="card glossary-search">
        <input value={term} onChange={e => setTerm(e.target.value)} onKeyDown={e => e.key === "Enter" && explain()} placeholder="Search e.g. hemoglobin" />
        <button className="primary-button" onClick={explain} disabled={loading}>{loading ? "Explaining…" : "Explain"}</button>
      </div>

      {result && (
        <div className="card">
          <span className="card-label">SIMPLE EXPLANATION</span>
          <h3>{term}</h3>
          <p>{result.definition}</p>
          {result.whyItMatters && (
            <>
              <span className="card-label">WHY IT MATTERS</span>
              <p>{result.whyItMatters}</p>
            </>
          )}
        </div>
      )}
    </section>
  );
}